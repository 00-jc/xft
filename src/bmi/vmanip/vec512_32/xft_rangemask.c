#include <xft/types/xft_p_vmanip_types.h>

#if XFT_HAS_512_VEC

__attribute__((__always_inline__, __flatten__, const, __used__))
inline t_u16a	xft_vrangemask512_32(t_vu32_512a v, t_u32 lo, t_u32 hi)
{
	return (xft_vmask512_32((t_vu32_512)(v - xft_vsplat512_32(lo)
			<= xft_vsplat512_32(hi - lo))));
}

#endif
