#include "xft_p_vmanip.h"

#if XFT_HAS_512_VEC

__attribute__((__always_inline__, __flatten__, const, __used__))
inline t_u32a	xft_vrangemask512_16(t_vu16_512a v, t_u16 lo, t_u16 hi)
{
	return (xft_vmask512_16((t_vu16_512)(v - xft_vsplat512_16(lo)
			<= xft_vsplat512_16(hi - lo))));
}

#endif
