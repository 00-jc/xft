#include <xft/bmi.h>
#include <xft/xft_p_syscalls.h>

#ifdef __linux__

# ifdef XFT_REQUIRE_LIBC

__attribute__((__nonnull__(1, 4), __always_inline__, __used__))
inline t_result	xft_open(const char *restrict path, int flags, t_u32a mode,
	int *restrict const fd)
{
	t_ssize	ret;

	ret = syscall(SYS_openat, xft_at_fdcwd, path, flags, mode);
	*fd = (int)xft_tern(ret < 0, (t_u64a)-1, (t_u64a)ret);
	return ((t_result){.ok = ret >= 0,
		.err = xft_tern(ret < 0, (t_u64a)errno, 0)});
}

# endif

#endif
