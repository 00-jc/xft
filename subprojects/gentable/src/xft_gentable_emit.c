static const t_gt_table	g_tables[] = {
{"start", sizeof("start") - 1, START},
{"continue", sizeof("continue") - 1, CONTINUE},
};

// nvec is >= 8 bytes in size so it's OK!
__attribute__((__nonnull__(1), __always_inline__, __hot__))
inline static t_u64	gt__hexlen(const t_u8 *__restrict__ const p, t_u64 max)
{
	t_nvec	vec;
	t_nmask	m;

	vec = xft_vmask_load(p, (t_nmask)((1ULL << xft_tern(max < 8, max, 8))
				- 1));
	m = xft_vrangemask(vec, '0', '9') | xft_vrangemask(vec | 0x20, 'a', 'f');
	return (xft_memctz_u64(~(0ULL | m)));
}

__attribute__((__nonnull__(1, 3), __always_inline__, __hot__))
inline static t_result	gt__emit_entry(t_writer *__restrict__ const w,
				t_buffer src, const t_gentable_entry *__restrict__ const e)
{
	t_u64	args[4];

	args[0] = (t_uptr)(src.mem + e->start);
	args[1] = gt__hexlen(src.mem + e->start, src.size - e->start);
	args[2] = args[0] + xft_tern(e->type & RANGE, args[1] + 2, 0);
	args[3] = gt__hexlen((const t_u8 *)args[2],
			src.size - (args[2] - (t_uptr)src.mem));
	return (xft_fmt_writer(w, xft_fatptr((t_u8 *)GT_ENTRY_FMT,
				sizeof(GT_ENTRY_FMT) - 1), args));
}

__attribute__((__nonnull__(1, 3, 4), __always_inline__))
inline static t_result	gt__emit_table(t_writer *__restrict__ const w,
				t_buffer src, const t_vec *__restrict__ const set,
				const t_gt_table *__restrict__ const tbl)
{
	const t_gentable_entry	*e;
	t_u64					args[3];
	t_result				ret;
	t_u64					i;

	args[0] = (t_uptr)tbl->name;
	args[1] = tbl->len;
	args[2] = 0;
	ret = xft_fmt_writer(w, xft_fatptr((t_u8 *)GT_HEADER_FMT,
				sizeof(GT_HEADER_FMT) - 1), args);
	i = 0;
	while (ret == OK && i < set->size)
	{
		e = (const t_gentable_entry *)(set->buf.mem + i);
		if (e->type & tbl->tag)
			ret = gt__emit_entry(w, src, e);
		args[2] += (e->type & tbl->tag) != 0;
		i += sizeof(t_gentable_entry);
	}
	if (__builtin_expect(ret == KO, 0))
		return (KO);
	return (xft_fmt_writer(w, xft_fatptr((t_u8 *)GT_EPILOGUE_FMT,
				sizeof(GT_EPILOGUE_FMT) - 1), args));
}

__attribute__((__nonnull__(1, 3), __always_inline__))
inline static t_result	gt__emit_body(t_writer *__restrict__ const w,
				t_buffer src, const t_vec *__restrict__ const set)
{
	t_result	ret;
	t_u64		i;

	ret = xft_writer_write(w, xft_fatptr((t_u8 *)g_prologue,
				sizeof(g_prologue) - 1));
	i = 0;
	while (ret == OK && i < sizeof(g_tables) / sizeof(*g_tables))
		ret = gt__emit_table(w, src, set, &g_tables[i++]);
	return (ret);
}

__attribute__((__nonnull__(2, 3)))
t_result	gt_emit(t_buffer src, const t_vec *__restrict__ const set,
				const char *__restrict__ const path)
{
	const int	fd = xft_open(path, xft_o_wronly | xft_o_creat
			| xft_o_trunc, 0644);
	static t_u8	buf[BUFSIZE];
	t_writer	w;
	t_result	ret;

	if (__builtin_expect(fd < 0, 0))
		return (KO);
	w = xft_get_fs_writer(xft_fatptr(buf, BUFSIZE), fd);
	ret = gt__emit_body(&w, src, set);
	if (__builtin_expect(ret == OK, 1))
		ret = xft_writer_flush(&w);
	xft_close(fd);
	return (ret);
}
