#ifndef XID_H
# define XID_H

# include "primitives.h"

// XID_Start and XID_Continue as inclusive [lo, hi] codepoint ranges,
// ascending and disjoint. generated by gentable from
// DerivedCoreProperties.txt, see xft_xid(3)
extern const t_u32	g_xid_start[][2];
extern const t_size	g_xid_start_len;
extern const t_u32	g_xid_continue[][2];
extern const t_size	g_xid_continue_len;

// XID_Start plus '_', and XID_Continue; ascii is answered without the
// tables
bool				xft_xid_is_start(t_u32 cp);
bool				xft_xid_is_continue(t_u32 cp);

// branchless utf8 decode of a loaded little endian word, 0 on invalid
// or overlong input. xft_xid_codepoint_len gives the encoded length of
// the lead byte, xft_xid_load_point loads up to 4 bytes of bytes[0, cap)
// with out of range bytes read as 0, so there is no overread
t_u32				xft_xid_decode(t_u32 w)\
						__attribute__((__hot__, __pure__));
t_u8				xft_xid_codepoint_len(t_u32a codepoint)\
						__attribute__((__const__));
t_u32a				xft_xid_load_point(const t_u8 *__restrict__ const bytes,
						t_size cap)\
						__attribute__((__nonnull__(1), __pure__));

#endif
